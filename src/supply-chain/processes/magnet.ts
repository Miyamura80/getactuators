// into a rotor. Step ids are stable: /bom nodes and #step= links use them.
// Numbers are the published figures of one source each; a range is the
// spread that source gives, not a world average.

const ROTOR_MAGNET = "rotor-magnet";

function num(
    label: string,
    value: number,
    unit: string,
    sources: string[],
    asOf: string,
    extra: Partial<Sourced<number>> = {},
): KeyNumber {
    return {
        label,
        value: {
            value,
            ...(unit ? { unit } : {}),
            sources,
            asOf,
            confidence: "reported",
            ...extra,
        },
    };
}

const range = (
    label: string,
    lo: number,
    hi: number,
    unit: string,
    sources: string[],
    asOf: string,
    note?: string,
): KeyNumber =>
    num(label, hi, unit, sources, asOf, {
        range: [lo, hi],
        ...(note ? { note } : {}),
    });

