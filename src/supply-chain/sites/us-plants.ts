// Mines, refineries and plants in the US for /us, including foreign-owned
// ones (e-VAC in Sumter, Schaeffler and Kaydon bearing plants, Ucore and
// Aclara in Louisiana, Cyclic Materials in Arizona) that show with an owner
// chip. Most pins are city centres ("city"); none is placed more precisely
// than its source. Announced and under-construction plants say so in
// `status`: the US chain is still mostly being built.

const reported = (
    value: number,
    unit: string,
    asOf: string,
    sources: SourceId[],
    note?: string,
): Sourced<number> => ({
    value,
    unit,
    sources,
    asOf,
    confidence: "reported",
    ...(note ? { note } : {}),
});

const opened = (year: number, sources: SourceId[], asOf = String(year)) =>
    reported(year, "year", asOf, sources);

type P = Parameters<typeof plant>[1];
type City = [admin1: string, lat: number, lon: number];

// A US plant at a city, with its status always stated.
const usPlant = (
    id: string,
    companyId: string,
    name: string,
    [admin1, lat, lon]: City,
    status: NonNullable<Site["status"]>,
    p: Omit<
        P,
        "companyId" | "name" | "country" | "admin1" | "lat" | "lon" | "precision"
    >,
): Site =>
    plant(id, {
        companyId,
        name,
        country: "US",
        admin1,
        lat,
        lon,
        precision: "city",
        status,
        ...p,
    });

