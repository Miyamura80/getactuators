// Headquarters and plants of the /korea companies, the Korean plants of
// foreign makers (NSK, Schaeffler, ASM), Korean-owned sites abroad and the
// foreign partner sites their supply links reach. Pins are city centres
// ("city") unless the source names only the province ("region").

const kr = (
    id: string,
    companyId: string,
    name: string,
    admin1: string,
    lat: number,
    lon: number,
    sources: string[],
): Site =>
    hq(id, {
        companyId,
        name: `${name} headquarters`,
        country: "KR",
        admin1,
        lat,
        lon,
        sources,
    });

const capacity = (
    value: number,
    unit: string,
    asOf: string,
    sources: string[],
    note?: string,
): Sourced<number> => ({
    value,
    unit,
    sources,
    asOf,
    confidence: "reported",
    ...(note ? { note } : {}),
});

