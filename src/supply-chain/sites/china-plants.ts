// Mines, plants and works in China for /china, including foreign-owned ones
// (Shanghai Fanuc, KUKA Shunde, the Proterial magnet joint venture) that show
// with an owner chip. Most pins are city centres ("city"); "region" means only
// the province is public. A status is left out when no source gives a current
// one.

const reported = (
    value: number,
    unit: string,
    asOf: string,
    sources: SourceId[],
    note?: string,
): Sourced<number> => ({
    value,
    unit,
    sources,
    asOf,
    confidence: "reported",
    ...(note ? { note } : {}),
});

const opened = (year: number, sources: SourceId[]): Sourced<number> =>
    reported(year, "year", String(year), sources);

type P = Parameters<typeof plant>[1];

// A plant in China. Unlike plant(), no "operating" default: the status is
// only what the record says (see the note above).
const cnPlant = (id: string, p: Omit<P, "country">): Site => {
    const { status: _default, ...site } = plant(id, { country: "CN", ...p });
    return p.status ? { ...site, status: p.status } : site;
};

