import { SINCE_YEAR } from "../../src/patents/landscape";
import {
    type CpcCode,
    TECHNOLOGIES,
    type Technology,
} from "../../src/patents/technologies";

// Builds the one BigQuery query behind /patents from src/patents/technologies.ts.
// One scan of the publications table returns a row per patent family that
// falls in any technology, with the technologies it falls in. Families are
// deduplicated by family_id; the priority date is the earliest in the family;
// the applicant is the first harmonised assignee of the earliest publication
// that names one. scripts/patents/queries/landscape.sql is this output,
// committed so a reviewer can read and rerun it in the BigQuery console.

export const DATASET = "patents-public-data.patents.publications";

function codeCondition(c: CpcCode): string {
    const value = c.match === "exact" ? `'${c.code}'` : `'${c.code}%'`;
    return c.match === "exact" ? `code = ${value}` : `code LIKE ${value}`;
}

function keywordRegex(words: readonly string[]): string {
    return `r'\\b(?:${words.map((w) => w.replace(/[^a-z0-9 ]/g, "")).join("|")})'`;
}

const col = (t: number, i: number) => `t${t}_c${i}`;

function familyFlags(techs: readonly Technology[]): string[] {
    return techs.flatMap((t, ti) =>
        t.cpc.flatMap((c, ci) => {
            const code = `LOGICAL_OR(EXISTS(SELECT 1 FROM UNNEST(codes) AS code WHERE ${codeCondition(c)})) AS ${col(ti, ci)}`;
            const kw = c.keywords
                ? [
                      `LOGICAL_OR(REGEXP_CONTAINS(text_en, ${keywordRegex(c.keywords)})) AS ${col(ti, ci)}_kw`,
                  ]
                : [];
            return [code, ...kw];
        }),
    );
}

function techMatch(t: Technology, ti: number): string {
    return t.cpc
        .map((c, ci) =>
            c.keywords ? `(${col(ti, ci)} AND ${col(ti, ci)}_kw)` : col(ti, ci),
        )
        .join(" OR ");
}

export function buildLandscapeSql(techs: readonly Technology[] = TECHNOLOGIES): string {
    const any = `            ${techs
        .flatMap((t) => t.cpc.map(codeCondition))
        .map((cond) => cond.replace("code", "c.code"))
        .join("\n            OR ")}`;
    const flags = familyFlags(techs)
        .map((f) => `        ${f}`)
        .join(",\n");
    const tech = techs
        .map((t, ti) => `            IF(${techMatch(t, ti)}, '${t.id}', NULL)`)
        .join(",\n");
    return `-- Generated by scripts/patents/sql.ts from src/patents/technologies.ts.
-- Do not edit by hand: change the technologies and run
--   bun scripts/patents/fetch.ts --write-queries
WITH pubs AS (
    SELECT
        p.family_id,
        p.publication_number,
        p.publication_date,
        p.priority_date,
        (SELECT ANY_VALUE(t.text) FROM UNNEST(p.title_localized) AS t WHERE t.language = 'en') AS title,
        LOWER(CONCAT(
            IFNULL((SELECT ANY_VALUE(t.text) FROM UNNEST(p.title_localized) AS t WHERE t.language = 'en'), ''),
            ' ',
            IFNULL((SELECT ANY_VALUE(a.text) FROM UNNEST(p.abstract_localized) AS a WHERE a.language = 'en'), '')
        )) AS text_en,
        IF(
            ARRAY_LENGTH(p.assignee_harmonized) > 0,
            STRUCT(p.assignee_harmonized[OFFSET(0)].name AS name, p.assignee_harmonized[OFFSET(0)].country_code AS country),
            NULL
        ) AS first_assignee,
        ARRAY(SELECT c.code FROM UNNEST(p.cpc) AS c) AS codes
    FROM \`${DATASET}\` AS p
    WHERE p.priority_date >= ${SINCE_YEAR}0101
        AND p.family_id != '-1'
        AND EXISTS (
            SELECT 1 FROM UNNEST(p.cpc) AS c WHERE
${any}
        )
),
families AS (
    SELECT
        family_id,
        MIN(priority_date) AS priority_date,
        ARRAY_AGG(publication_number ORDER BY publication_date LIMIT 1)[OFFSET(0)] AS publication,
        ARRAY_AGG(title IGNORE NULLS ORDER BY publication_date LIMIT 1)[SAFE_OFFSET(0)] AS title,
        ARRAY_AGG(first_assignee IGNORE NULLS ORDER BY publication_date LIMIT 1)[SAFE_OFFSET(0)] AS applicant,
${flags}
    FROM pubs
    GROUP BY family_id
)
SELECT
    family_id,
    priority_date,
    publication,
    title,
    applicant.name AS assignee,
    applicant.country AS country,
    ARRAY_TO_STRING(
        ARRAY(SELECT x FROM UNNEST([
${tech}
        ]) AS x WHERE x IS NOT NULL),
        ','
    ) AS technologies
FROM families
WHERE ${techs.map((t, ti) => `(${techMatch(t, ti)})`).join("\n    OR ")}
ORDER BY family_id
`;
}
